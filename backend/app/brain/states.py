"""Enums shared by the parser, engine, schemas, and API.

Persisted conversation states are intentionally only five. Availability checks
and execution happen as *events* inside a turn, not as stored states.
"""
from enum import Enum


class State(str, Enum):
    IDLE = "IDLE"
    COLLECTING = "COLLECTING"
    AWAITING_CONFIRMATION = "AWAITING_CONFIRMATION"
    DISAMBIGUATING = "DISAMBIGUATING"
    COMPLETED = "COMPLETED"


class Flow(str, Enum):
    BOOK = "BOOK"
    RESCHEDULE = "RESCHEDULE"
    CANCEL = "CANCEL"


class Intent(str, Enum):
    BOOK_APPOINTMENT = "BOOK_APPOINTMENT"
    RESCHEDULE_APPOINTMENT = "RESCHEDULE_APPOINTMENT"
    CANCEL_APPOINTMENT = "CANCEL_APPOINTMENT"
    CONFIRM = "CONFIRM"
    DECLINE = "DECLINE"
    CORRECT_INFORMATION = "CORRECT_INFORMATION"
    CANCEL_CONVERSATION = "CANCEL_CONVERSATION"
    SELECT_OPTION = "SELECT_OPTION"
    PROVIDE_INFORMATION = "PROVIDE_INFORMATION"
    UNSUPPORTED = "UNSUPPORTED"
    GREETING_GOODBYE = "GREETING_GOODBYE"
    UNKNOWN = "UNKNOWN"


class EventKind(str, Enum):
    TURN_RECEIVED = "TURN_RECEIVED"
    PARSED = "PARSED"
    EMPTY_INPUT = "EMPTY_INPUT"
    LOW_CONFIDENCE = "LOW_CONFIDENCE"
    ENTITY_UPDATED = "ENTITY_UPDATED"
    STATE_TRANSITION = "STATE_TRANSITION"
    INTENT_SWITCH = "INTENT_SWITCH"
    AVAILABILITY_CHECK = "AVAILABILITY_CHECK"
    ALTERNATIVES_OFFERED = "ALTERNATIVES_OFFERED"
    APPOINTMENT_LOOKUP = "APPOINTMENT_LOOKUP"
    CONFIRMATION_PROPOSED = "CONFIRMATION_PROPOSED"   # pending, nothing saved
    CONFIRMATION_ACCEPTED = "CONFIRMATION_ACCEPTED"
    CONFIRMATION_DECLINED = "CONFIRMATION_DECLINED"
    STALE_PENDING_CLEARED = "STALE_PENDING_CLEARED"
    DB_WRITE = "DB_WRITE"                             # real mutation (executed=True)
    REFUSED = "REFUSED"
    UNSUPPORTED_REQUEST = "UNSUPPORTED_REQUEST"
    DUPLICATE_TURN = "DUPLICATE_TURN"
    ERROR = "ERROR"